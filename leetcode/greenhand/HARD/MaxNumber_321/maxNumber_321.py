def maxSubnum(nums,k):
    n = len(nums)

    dp = [[0] * (k + 1) for _ in range(n)]
    dp[n - 1][1] = nums[n-1]
    for i in range(n - 2, -1, -1):
        for j in range(1, k + 1):
            dp[i][j] = max(dp[i + 1][j], (nums[i] * 10 ** (j - 1) + dp[i + 1][j - 1]) if n - i > j - 1 else 0)

    return dp[0][k]



class Solution:
    def maxNumber(self, nums1, nums2, k: int):

        ans = 0
        n=len(nums1)
        m=len(nums2)
        l=max(0,k-len(nums2))
        r=min(k,len(nums1))


        for i in range(l,r+1):
            if i==0:
                merge1=[]
            else:
                merge1=maxSubnum(nums1,i)
                merge1 = [int(x) for x in list(str(merge1))]

            if i==k:
                merge2=[]
            else:
                merge2=maxSubnum(nums2,k-i)
                merge2=[int(x) for x in list(str(merge2))]

            total = 0
            p1 = 0
            p2 = 0
            while True:
                if p1 < i and p2 < k - i:
                    if merge1[p1] < merge2[p2]:
                        total = total * 10 + merge2[p2]
                        p2 += 1
                    elif merge1[p1]==merge2[p2]:
                        tmp1,tmp2=p1+1,p2+1
                        while tmp1<i and tmp2<k-i and merge1[tmp1]==merge2[tmp2]:
                            tmp1+=1
                            tmp2+=1
                        if tmp1==i or (tmp2<k-i and merge1[tmp1]<merge2[tmp2]):
                            total=total*10+merge2[p2]
                            p2+=1
                        else:
                            total=total*10+merge1[p1]
                            p1+=1
                    else:
                        total = total * 10 + merge1[p1]
                        p1 += 1

                if p1 == i:
                    while p2 < k - i:
                        total = total * 10 + merge2[p2]
                        p2 += 1

                if p2 == k - i:
                    while p1 < i:
                        total = total * 10 + merge1[p1]
                        p1 += 1

                if p1 == i and p2 == k - i:
                    break
            ans = max(ans, total)

        res = []
        while ans > 0:
            res.append(ans % 10)
            ans //= 10
        return res[::-1]





