class Solution:
    def eventualSafeNodes(self, graph):
        n = len(graph)
        color = [0] * n

        def safe(i):
            if color[i] > 0:
                return color[i] == 2
            color[i] = 1

            if not graph[i]:
                color[i] = 2
                return True

            for next in graph[i]:
                if not safe(next):
                    return False

            color[i] = 2
            return True

        return [x for x in range(n) if safe(x)]


