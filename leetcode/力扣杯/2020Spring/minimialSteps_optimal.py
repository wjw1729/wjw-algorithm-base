from collections import deque
import time


class Solution:
    def minimalSteps(self, maze):
        m = len(maze)
        n = len(maze[0])

        mech = []
        start = (0, 0)
        stones = []
        end = (0, 0)

        for i in range(m):
            for j in range(n):
                if maze[i][j] == "S":
                    start = (i, j)

                if maze[i][j] == "T":
                    end = (i, j)
                if maze[i][j] == "M":
                    mech.append((i, j))
                if maze[i][j] == "O":
                    stones.append((i, j))
        mech = [start] + mech
        stones = [end] + stones

        ls = len(mech)
        lt = len(stones)

        # 找到mech中第i个点到stones中第j个点的最短距离
        def bfs(i, j):

            queue = deque()
            queue.append((mech[i][0], mech[i][1], 0))
            bin = set()
            bin.add(mech[i])

            while queue:
                r, c, level = queue.popleft()

                for x, y in [(r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)]:
                    if 0 <= x < m and 0 <= y < n and (x, y) not in bin:
                        if (x, y) == stones[j]:
                            return level + 1
                        if maze[x][y] != '#':
                            queue.append((x, y, level + 1))
                            bin.add((x, y))
            return float('inf')

        adj = [[0] * lt for _ in range(ls)]

        for i in range(ls):
            for j in range(lt):
                adj[i][j] = bfs(i, j)
                if len(mech) == 1:  # 没有机关，直接返回adj[0][0]
                    return adj[0][0] if adj[0][0] != float('inf') else -1
            if adj[i][1:] == [float('inf')] * (lt - 1):  # 石头取不到，返回-1
                return -1

        dis = [[float("inf")] * ls for _ in range(ls)]

        for i in range(ls):
            for j in range(i + 1, ls):
                for k in range(1, lt):
                    dis[i][j] = min(dis[i][j], adj[i][k] + adj[j][k])

        f = [[float('inf')] * (ls - 1) for _ in range(1 << (ls - 1))]
        for i in range(ls - 1):
            f[1 << i][i] = dis[0][i + 1]

        for mask in range(1, 1 << (ls - 1)):
            for i in range(ls - 1):
                if mask & (1 << i) != 0:  # i在mask里面
                    for j in range(ls - 1):
                        if mask & (1 << j) == 0:  # j不在mask里面。
                            next = mask | (1 << j)
                            if f[next][j] > f[mask][i] + (dis[i + 1][j + 1] if i < j else dis[j + 1][i + 1]):
                                f[next][j] = f[mask][i] + (dis[i + 1][j + 1] if i < j else dis[j + 1][i + 1])

        ans = float('inf')
        for i in range(ls - 1):
            ans = min(ans, f[(1 << (ls - 1)) - 1][i] + adj[i + 1][0])

        return ans if ans != float('inf') else -1


