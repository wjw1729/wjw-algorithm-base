from collections import deque
class Solution:
    def minimumTotalDistance(self, robot, factory) -> int:



        xls=robot
        yls=[]

        for x,y in factory:
            yls+=[x]*y

        n=max(len(xls),len(yls))

        g=[[-float('inf')]*n for _ in range(n)]

        for i in range(n):
            if i>=len(xls):
                g[i]=[0]*n
                continue
            for j in range(n):
                g[i][j]=max(g[i][j],-abs(xls[i]-yls[j]))

        lx,ly,slack=[-float('inf')]*n,[0]*n,[0]*n

        matchx,matchy=[-1]*n,[-1]*n
        pre=[-1]*n
        vx,vy=[False]*n,[False]*n

        q=deque()


        def check(v):
            vy[v]=True
            if matchy[v]!=-1:
                q.append(matchy[v])
                vx[matchy[v]]=True
                return False

            while v!=-1:
                matchy[v]=pre[v]

                t=matchx[pre[v]]
                matchx[pre[v]]=v
                v=t

            return True

        def bfs(i):
            while q:
                q.pop()
            q.append(i)
            vx[i]=True
            while 1:
                while q:
                    u=q.popleft()

                    for v in range(n):
                        if not vy[v]:
                            delta=lx[u]+ly[v]-g[u][v]
                            if slack[v]>=delta:
                                pre[v]=u
                                if delta:
                                    slack[v]=delta
                                elif check(v):
                                    return

                a=float('inf')
                for j in range(n):
                    if not vy[j]:
                        a=min(a,slack[j])

                for j in range(n):
                    if vx[j]:
                        lx[j]-=a

                    if vy[j]:
                        ly[j]+=a
                    else:
                        slack[j]-=a

                for j in range(n):
                    if not vy[j] and slack[j]==0 and check(j):
                        return

        for i in range(n):
            for j in range(n):
                lx[i]=max(lx[i],g[i][j])

        for i in range(n):
            for j in range(n):
                slack[j]=float('inf')
                vx[j]=False
                vy[j]=False

            bfs(i)

        res=0
        for i in range(n):
            if g[i][matchx[i]]>-float('inf'):
                res+=g[i][matchx[i]]

            else:
                matchx[i]=-1

        for i in range(len(xls)):
            print(matchx[i])

        return -res



