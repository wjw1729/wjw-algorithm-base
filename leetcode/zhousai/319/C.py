class Solution:
    def subarrayLCM(self, nums, k: int) -> int:

        @lru_cache(None)
        def mygcd(i,j):
            if i==j:
                return nums[i]
            if i>j:
                return 1

            mid=(i+j)//2
            a=mygcd(i,mid)
            b=mygcd(mid+1,j)

            return a*b//math.gcd(a,b)


        n=len(nums)
        ans=0
        for i in range(n):
            for j in range(i,n):
                if mygcd(i,j)==k:
                    ans+=1

        return ans

