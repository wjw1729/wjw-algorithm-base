from sortedcontainers import SortedList


class Solution:
    def getBiggestThree(self, grid):

        m = len(grid)
        n = len(grid[0])
        ans = SortedList([0, 0, 0])
        for i in range(m):
            for j in range(n):

                p = min(min(j, n - 1 - j), (m - 1 - i) // 2)
                sl_sum = grid[i][j]
                if sl_sum not in ans and sl_sum > ans[0]:
                    ans.pop(0)
                    ans.add(sl_sum)

                for k in range(1, p + 1):
                    sl_sum = 0
                    for k_index in range(k + 1):
                        sl_sum += grid[i + k_index][j - k_index] + grid[i + k_index][j + k_index]
                        sl_sum += grid[i + 2 * k - k_index][j - k_index] + grid[i + 2 * k - k_index][j + k_index]
                    sl_sum -= (grid[i][j] + grid[i + k][j - k] + grid[i + 2 * k][j] + grid[i + k][j + k])
                    if sl_sum not in ans and sl_sum > ans[0]:
                        ans.pop(0)
                        ans.add(sl_sum)
        ans = list(reversed(ans))
        while 0 in ans:
            ans.remove(0)
        return ans


