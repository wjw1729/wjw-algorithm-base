class Solution:
    def minimumOperations(self, nums, start: int, goal: int) -> int:
        dp = [float('inf')] * (1001)

        visited = set()
        visited.add(start)

        dp[start] = 0
        while len(visited) < 10001:
            tmp = set()
            for i in visited:
                for num in nums:
                    if i + num == goal:
                        return dp[i] + 1
                    elif 0 <= i + num <= 1000 and i + num not in visited:
                        if i+num==836:
                            print(1)
                        dp[i + num] = min(dp[i + num], dp[i] + 1)
                        tmp.add(i + num)
                    if i - num == goal:
                        return dp[i] + 1
                    elif 0 <= i - num <= 1000 and i - num not in visited:
                        if i-num==836:
                            print(1)
                        dp[i - num] = min(dp[i - num], dp[i] + 1)
                        tmp.add(i - num)

                    if i ^ num == goal:
                        return dp[i] + 1
                    elif 0 <= i ^ num <= 1000 and i ^ num not in visited:
                        if i^num==836:
                            print(1)
                        dp[i ^ num] = min(dp[i ^ num], dp[i] + 1)
                        tmp.add(i ^ num)
            if tmp==set():
                break
            visited |= tmp
        return -1

