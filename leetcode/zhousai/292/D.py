from collections import deque
class Solution:
    def hasValidPath(self, grid) -> bool:

        m=len(grid)
        n=len(grid[0])
        if (m+n-1)%2!=0:
            return False
        if grid[0][0]==')':
            return False
        f=[[set() for _ in range(n)] for _ in range(m)]
        f[0][0]={1}


        for i in range(m):
            for j in range(n):
                if j-1>=0:
                    for x in f[i][j-1]:
                        tmp=x+(1 if grid[i][j]=='(' else -1)
                        if tmp>=0:
                            f[i][j].add(tmp)
                if i-1>=0:
                    for x in f[i-1][j]:
                        tmp = x + (1 if grid[i][j] == '(' else -1)
                        if tmp>=0:
                            f[i][j].add(tmp)

        return 0 in f[m-1][n-1]



