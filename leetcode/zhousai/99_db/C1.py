from collections import defaultdict


class Solution:
    def findValidSplit(self, nums) -> int:

        n = len(nums)
        idx = defaultdict(lambda: [n, 0])


        for i in range(n):
            x = nums[i]
            for j in range(2,x):
                if j*j>x:
                    break
                if x % j == 0:
                    idx[j][0] = min(idx[j][0], i)
                    idx[j][1] = max(idx[j][1], i)

                    while x % j == 0:
                        x //= j
            if x>1:
                idx[x][0]=min(idx[x][0],i)
                idx[x][1]=max(idx[x][1],i)

        qls = list(idx.values())
        qls.sort()

        s = 0
        i = 0
        while i < len(qls) and s >= qls[i][0]:
            s = max(qls[i][1], s)
            i += 1

        return s if s < n - 1 else -1


